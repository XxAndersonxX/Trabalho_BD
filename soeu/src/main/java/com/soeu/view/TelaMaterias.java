 private void carregarMateriais() {
    try {
        Disciplina disciplina = (Disciplina) jComboBox1.getSelectedItem();

        if (disciplina == null) {
            return;
        }

        MaterialService materialService = new MaterialService();

        List<Material> materiais =
                materialService.readByDisciplina(disciplina.getCodigo());

        DefaultTableModel modelo =
                (DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0);

        for (Material material : materiais) {
            modelo.addRow(new Object[]{
                material.getTipo(),
                material.getNomeArquivo(),
                material.getLink()
            });
        }

    } catch (RuntimeException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}   
 
private void carregarDisciplinas() {
    try {
        DisciplinaService disciplinaService = new DisciplinaService();

        jComboBox1.removeAllItems();

        for (Disciplina disciplina : disciplinaService.listarTodas()) {
            jComboBox1.addItem(disciplina);
        }

    } catch (RuntimeException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

