    private void btEscolherActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEscolherActionPerformed

    JFileChooser chooser = new JFileChooser();

    int resultado = chooser.showOpenDialog(this);

    if (resultado == JFileChooser.APPROVE_OPTION) {
        arquivoSelecionado = chooser.getSelectedFile();

        JOptionPane.showMessageDialog(
            this,
            "Arquivo selecionado: " + arquivoSelecionado.getName()
        );
    }

    }//GEN-LAST:event_btEscolherActionPerformed

    private void btSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btSalvarActionPerformed

    try {
        Disciplina disciplina = (Disciplina) jComboBox1.getSelectedItem();

        if (disciplina == null) {
            JOptionPane.showMessageDialog(this, "Selecione uma disciplina.");
            return;
        }

        if (arquivoSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Selecione um arquivo.");
            return;
        }

        byte[] arquivoBytes = Files.readAllBytes(arquivoSelecionado.toPath());

        Material material = new Material();

        material.setTipo("Arquivo");
        material.setLink("");
        material.setNomeArquivo(arquivoSelecionado.getName());
        material.setArquivo(arquivoBytes);
        material.setDisciplina(disciplina);

        MaterialService materialService = new MaterialService();
        materialService.create(material);

        JOptionPane.showMessageDialog(this, "Material salvo com sucesso!");

        carregarMateriais();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
        
    }//GEN-LAST:event_btSalvarActionPerformed

